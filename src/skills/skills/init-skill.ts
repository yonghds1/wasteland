/**
 * init-skill.ts - 项目初始化技能
 *
 * 初始化 CLAUDE.md 文件，生成项目上下文文档。
 */

import { join } from "node:path";
import { t } from "../../locales/index.js";
import type {
  Skill,
  SkillArgs,
  SkillExecutionContext,
  SkillResult,
} from "../skill-types.js";

/**
 * CLAUDE.md 默认模板
 */
